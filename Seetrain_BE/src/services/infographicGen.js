function createHeroPrompt(trainingContent) {
  const concepts = trainingContent.sections
    .map((section) => section.visualConcept.subject)
    .join(", ");

  return `
Create a professional hero illustration for an educational infographic.

Main topic: ${trainingContent.title}
Summary: ${trainingContent.summary}
Visual concepts: ${concepts}

Style:
- Modern educational 3D digital illustration.
- Consistent blue, cyan and white color palette.
- Attractive central composition.
- Soft lighting and subtle depth.
- Professional training poster quality.

Create visual artwork only.
No text, letters, numbers, captions, logos or watermarks.
`.trim();
}

function createSectionPrompt(trainingContent, section) {
  const concept = section.visualConcept;

  return `
Create a unique standalone educational illustration.

Overall topic: ${trainingContent.title}
Section: ${section.heading}

Main subject: ${concept.subject}
Action: ${concept.action}
Environment: ${concept.environment}

Key information:
${section.keyPoints.join("; ")}

Visual direction:
- Clearly depict the specified subject and action.
- Follow the visual concept instead of inventing a generic office scene.
- Use a recognizable visual metaphor.
- Do not depict a person sitting at a computer unless explicitly required.
- Use a modern educational 3D digital illustration style.
- Professional blue, cyan and white color palette.
- Clear composition with one dominant subject.
- Suitable for a small infographic card.
- No text, letters, numbers, captions, logos or watermarks.

The illustration must look visually distinct from illustrations
representing other sections.
`.trim();
}

function generateInfographicData(trainingContent) {
  if (
    !trainingContent ||
    typeof trainingContent.title !== "string" ||
    !Array.isArray(trainingContent.sections) ||
    trainingContent.sections.length === 0
  ) {
    throw new Error("Invalid training content");
  }

  const sections = trainingContent.sections.map((section, index) => {
    if (!section.visualConcept) {
      throw new Error(`Missing visual concept in section ${section.heading}`);
    }

    return {
      id: section.id || index + 1,
      heading: section.heading,
      points: section.keyPoints.slice(0, 4),
      narration: section.narration,
      visualConcept: section.visualConcept,
      imagePrompt: createSectionPrompt(trainingContent, section),
      imageDataUrl: null,
    };
  });

  return {
    title: trainingContent.title,
    subtitle: trainingContent.summary,
    imagePrompt: createHeroPrompt(trainingContent),
    sections,
    heroImageDataUrl: null,
    footer: "Generated by SeeTrain",
  };
}

module.exports = {
  generateInfographicData,
  genInfographicData: generateInfographicData,
};
